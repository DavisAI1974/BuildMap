// Optional scoped browser check. Reads a synthetic project; never runs it.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import { once } from 'node:events';
const { chromium } = await import(process.env.BUILDMAP_PLAYWRIGHT_MODULE || 'playwright-core');
import { startServer } from '../src/server.js';
import { scanProject } from '../src/scan.js';
import { snapshotHtml } from '../src/export.js';

const checks = [], errors = [], servers = [];
const check = text => { checks.push(text); console.log('PASS ' + text); };
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'buildmap-workflow-browser-'));
const source = await fs.readFile(new URL('../tests/fixtures/frankie-workflow.py', import.meta.url), 'utf8');
const listen = async server => { servers.push(server); await once(server, 'listening'); return `http://127.0.0.1:${server.address().port}`; };
let browser;
try {
  await fs.writeFile(path.join(root, 'workflow.py'), source.replaceAll('raw.csv', '<img onerror=evil()>.csv'));
  browser = await chromium.launch({ executablePath: process.env.BUILDMAP_BROWSER_EXECUTABLE || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  context.setDefaultTimeout(5000);
  const page = await context.newPage(); page.on('pageerror', e => errors.push(e.message));
  const base = await listen(startServer({ root, port: 0 }));
  await page.goto(base); await page.locator('.node').first().waitFor();
  await page.locator('#fitButton').click();
  await page.locator('.node[data-id="__mission__"]').click();
  await page.locator('.guide-open').click();
  await page.locator('.workflow-review').waitFor();
  assert.match(await page.locator('.workflow-review').innerText(), /Project-wide.*1\/1.*4 review finding/s);
  assert.equal(await page.locator('.workflow-finding').count(), 4);
  assert.match(await page.locator('#stateCounts').innerText(), /verified: 0.*live: 0/s);
  check('Project-wide report opens from the free map; four synthetic findings, no elevated proof');
  const reads = page.locator('.workflow-finding').filter({ hasText: 'possible repeated reads' });
  await reads.locator('summary').first().click();
  assert.match(await reads.innerText(), /Needs runtime evidence/);
  assert.match(await reads.innerText(), /CouplingJobs/); assert.match(await reads.innerText(), /CellJobSubset/);
  assert.match(await reads.innerText(), /partner_fft_cache/); assert.match(await reads.innerText(), /exact_pair_reuse/);
  assert.equal(await page.locator('#detail img').count(), 0);
  await reads.locator('.workflow-source').first().click();
  const opened = page.locator('.code-function[open]');
  assert.equal(await opened.count(), 1); assert.match(await opened.innerText(), /prepare/);
  assert.match(await page.locator('.workflow-product').first().innerText(), /Possible shared product/);
  check('Escaped filename, existing optimization cues and evidence navigation to exact calculation');
  const comp = page.locator('.workflow-finding').filter({ hasText: 'Workflow.jobs:' });
  await comp.locator('summary').first().click();
  assert.match(await comp.innerText(), /eager container.*cells.*transforms.*series/s);
  await comp.locator('.workflow-source').first().click();
  assert.match(await page.locator('.code-function[open]').filter({ hasText: 'Workflow.jobs' }).innerText(), /Workflow.jobs/);
  const calculation = page.locator('.workflow-calculation').filter({ hasText: 'What is Workflow.jobs building?' });
  await calculation.locator('summary').click();
  assert.match(await calculation.innerText(), /eager-container.*eligible\(x\)/s);
  check('Class method and filtered comprehension render and navigate without claiming runtime job counts');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.workflow-finding').first().locator('summary').first().click();
  const bounds = await page.evaluate(() => ({ viewport: innerWidth, width: document.documentElement.scrollWidth }));
  assert.ok(bounds.width <= bounds.viewport + 1, JSON.stringify(bounds));
  check('Expanded risk report fits 390px document width');
  await page.locator('.guide-back').click();
  assert.match(await page.locator('#detail').innerText(), /PIECE INSPECTOR/);
  assert.equal(await page.locator('#mapShell').isVisible(), true);
  assert.ok(await page.locator('#detail .file-list').count());
  check('Returning to free inspector retains map and full file inventory');
  const html = snapshotHtml(scanProject(root));
  let requests = [];
  const snapshotUrl = await listen(http.createServer((req, res) => { requests.push(req.url); res.writeHead(200, { 'content-type': 'text/html' }); res.end(html); }).listen(0, '127.0.0.1'));
  const offline = await context.newPage(); offline.on('pageerror', e => errors.push(e.message));
  await offline.goto(snapshotUrl); await offline.locator('.node').first().waitFor(); await offline.locator('#fitButton').click();
  await offline.locator('.node[data-id="__mission__"]').click(); await offline.locator('.guide-open').click();
  assert.equal(await offline.locator('.workflow-finding').count(), 4);
  assert.match(await offline.locator('#detail').innerText(), /Captured code reading/);
  assert.deepEqual(requests.filter(p => p !== '/favicon.ico'), ['/']);
  check('Self-contained captured report renders with no asset/API/poll requests');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('.guide-open').click();
  await fs.writeFile(path.join(root, 'workflow.py'), 'def search():\n    return 1\n');
  await page.waitForFunction(() => document.querySelector('.workflow-review')?.textContent.includes('0 review finding'));
  assert.equal(await page.locator('.workflow-finding').count(), 0);
  assert.equal(await page.locator('.code-function').count(), 1);
  check('Live source refresh removes outdated findings and calculations');
  await fs.writeFile(path.join(root, 'workflow.py'), 'def invalid(:\n');
  await page.waitForFunction(() => document.querySelector('.workflow-review')?.textContent.includes('parse-error'));
  assert.match(await page.locator('.workflow-review').innerText(), /0\/1.*No findings is not clearance/s);
  assert.deepEqual(errors, []);
  check('Parse failure stays visible as unreviewed scope; no page errors');
  console.log(JSON.stringify({ checkedAt: new Date().toISOString(), node: process.version, browser: browser.version(), checks, errors }, null, 2));
} finally {
  if (browser) await browser.close();
  await Promise.all(servers.map(s => new Promise(resolve => { s.closeAllConnections(); s.close(resolve); })));
  await fs.rm(root, { recursive: true, force: true });
}
